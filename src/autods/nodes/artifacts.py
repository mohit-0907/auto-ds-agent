"""Run artifacts: the retrained best model, the feature code, and run.json. No LLM.

artifacts_node (after the arena) retrains the winner on every row and saves it
with the metadata needed to use it correctly. finalize_node (last) writes
run.json, so the recorded cost includes the reporter's call.

The saved model is a plain dict, not an autods class: unpickling a custom class
needs autods installed, a dict of standard types plus a scikit-learn model only
needs scikit-learn. Like every pickle/joblib file, loading it executes code --
only load files you created.

Known limitation (v1): generated feature code is batch-stateless. It computes
medians and categories from whatever frame it receives, so predicting on new
data means running fe_code.py on a batch and aligning to feature_columns; a
single row cannot be featurized faithfully.
"""

from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path
from typing import Any

import joblib
import pandas as pd
import structlog

from autods.arena.candidates import candidates
from autods.arena.scoring import prepare_xy
from autods.config import (
    CV_FOLDS,
    FE_CODEGEN_MODEL,
    MAX_FE_ATTEMPTS,
    RANDOM_STATE,
    REPORTER_MODEL,
    ROUTER_MODEL,
    SELECTION_MIN_FOLD_WIN_RATE,
)
from autods.state import AgentState

log = structlog.get_logger(__name__)

BUNDLE_FILE = "best_pipeline.joblib"
FE_CODE_FILE = "fe_code.py"
RUN_RECORD_FILE = "run.json"
BUNDLE_FORMAT_VERSION = 1

_FALLBACK_NOTE = '''"""Features for this run came from the deterministic fallback recipe.

No generated code was used.

Reproduce them with:

    from autods.nodes.fallback_fe import basic_features
    features = basic_features(df, target_column)

Recipe: median-impute numeric columns, drop consecutive-integer ID columns,
one-hot encode text columns with at most 20 levels (missing as its own level),
drop other text, datetime and all-missing columns. Leaky encoded columns are
dropped by the fallback node.
"""
'''


def _fe_source(state: AgentState) -> str:
    processed = state["processed_data_path"] or ""
    if "fallback" in processed:
        return "fallback"
    return f"generated (attempt {len(state['fe_code_history'])})"


def _fe_code_text(state: AgentState) -> str:
    if _fe_source(state) == "fallback":
        return _FALLBACK_NOTE
    # The loop stops at the first passing attempt, so the last code is the one used.
    header = (
        f"# Feature engineering code for {Path(state['dataset_path']).name}, generated by "
        f"{FE_CODEGEN_MODEL}\n# ({_fe_source(state)}). Batch-stateless: run it on a batch and "
        "align the result to feature_columns in best_pipeline.joblib.\n\n"
    )
    return header + state["fe_code_history"][-1]


def artifacts_node(state: AgentState) -> dict[str, Any]:
    """Graph node: retrain the best model on all rows; save it and the feature code.

    Args:
        state: Reads best_model_id, processed_data_path, task_decision, run_dir,
            fe_code_history, dataset_path.

    Returns:
        An empty dict on success (the files are the output), a warning if the
        refit failed, or an empty dict when there is no best model to save.

    Raises:
        ValueError: If run_dir is not set (a wiring bug, as in the other file-writing nodes).
    """
    best_id, path, decision = (
        state["best_model_id"],
        state["processed_data_path"],
        state["task_decision"],
    )
    if best_id is None or path is None or decision is None:
        return {}
    if not state["run_dir"]:
        raise ValueError("state['run_dir'] must be set before the artifacts node runs")
    run_dir = Path(state["run_dir"])

    # Missing-target rows are dropped exactly as in the arena; the arena already reported it.
    X, y, class_names, _ = prepare_xy(
        pd.read_parquet(path), decision.target_column, decision.task_type
    )
    candidate = next(c for c in candidates(decision.task_type) if c.model_id == best_id)
    try:
        model = candidate.estimator.fit(X, y)
    except Exception as exc:  # any estimator error; the report still gets written
        log.warning("artifacts.refit_failed", model_id=best_id, error=str(exc))
        return {"warnings": [f"Could not retrain {candidate.model_name} on all rows: {exc}"]}

    bundle = {
        "format_version": BUNDLE_FORMAT_VERSION,
        "model": model,
        "model_id": best_id,
        "model_name": candidate.model_name,
        "task_type": decision.task_type,
        "target_column": decision.target_column,
        "feature_columns": list(X.columns),
        # The model predicts 0..k-1; class_names[i] is what code i means.
        "class_names": class_names,
        "trained_rows": len(X),
        "fe_source": _fe_source(state),
        "random_state": RANDOM_STATE,
        "created_at": datetime.now().isoformat(timespec="seconds"),
    }
    joblib.dump(bundle, run_dir / BUNDLE_FILE)
    (run_dir / FE_CODE_FILE).write_text(_fe_code_text(state), encoding="utf-8")
    log.info("artifacts.saved", model_id=best_id, rows=len(X), features=X.shape[1])
    return {}


def run_record(state: AgentState) -> dict[str, Any]:
    """Everything the run decided, as plain JSON-ready data. No secrets: model names, never keys.

    Args:
        state: The run's final state.

    Returns:
        The content of run.json.
    """
    profile, decision = state["data_profile"], state["task_decision"]
    run_dir = Path(state["run_dir"])
    attempts = [
        {
            "attempt": i,
            "explanation": explanation,
            "outcome": (
                state["tracebacks"][i - 1].splitlines()[0]
                if i <= len(state["tracebacks"])
                else "passed validation"
            ),
            "code_file": f"fe/attempt_{i}/generated_fe.py",
        }
        for i, explanation in enumerate(state["fe_explanations"], start=1)
    ]
    return {
        "inputs": {
            "dataset_path": state["dataset_path"],
            "user_description": state["user_description"],
            "target_column": state["target_column"],
        },
        "config": {
            "router_model": ROUTER_MODEL,
            "fe_codegen_model": FE_CODEGEN_MODEL,
            "reporter_model": REPORTER_MODEL,
            "max_fe_attempts": MAX_FE_ATTEMPTS,
            "cv_folds": CV_FOLDS,
            "random_state": RANDOM_STATE,
            "selection_min_fold_win_rate": SELECTION_MIN_FOLD_WIN_RATE,
        },
        "profile": None
        if profile is None
        else {
            "n_rows": profile.n_rows,
            "n_cols": profile.n_cols,
            "columns_truncated": profile.columns_truncated,
        },
        "task_decision": None if decision is None else decision.model_dump(),
        "feature_engineering": {
            "attempts": attempts,
            "final_source": _fe_source(state) if state["processed_data_path"] else None,
        },
        "leaderboard": [r.model_dump() for r in state["leaderboard"]],
        "best_model_id": state["best_model_id"],
        "warnings": state["warnings"],
        "token_cost_usd": round(state["token_cost_usd"], 6),
        "artifacts": sorted(p.name for p in run_dir.iterdir()) if run_dir.is_dir() else [],
        "finished_at": datetime.now().isoformat(timespec="seconds"),
    }


def finalize_node(state: AgentState) -> dict[str, Any]:
    """Graph node, last: write run.json into run_dir.

    Raises:
        ValueError: If run_dir is not set.
    """
    if not state["run_dir"]:
        raise ValueError("state['run_dir'] must be set before the finalize node runs")
    path = Path(state["run_dir"]) / RUN_RECORD_FILE
    path.write_text(json.dumps(run_record(state), indent=2, default=str), encoding="utf-8")
    log.info("run.finished", run_record=str(path), cost_usd=round(state["token_cost_usd"], 4))
    return {}
